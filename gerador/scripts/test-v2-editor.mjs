import { chromium } from 'playwright';
import { createServer } from '../node_modules/vite/dist/node/index.js';
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import assert from 'node:assert/strict';
const root = fileURLToPath(new URL('../', import.meta.url));
const artifacts = path.join(root, 'artifacts/v2-editor');
await mkdir(artifacts, { recursive: true });
const server = await createServer({ root, configFile: path.join(root, 'vite.config.ts'), server: { host: '127.0.0.1', port: 5187, strictPort: true, open: false, watch: { ignored: ['**/artifacts/**'] } } });
await server.listen();
let browser;
let page;
try {
    browser = await chromium.launch();
    page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    const errors = []; page.on('pageerror', e => errors.push(e.stack));
    await page.goto('http://127.0.0.1:5187/gerador-de-proposta/v2.html');
    const pdf = page.getByRole('button', { name: 'Gerar PDF', exact: true });
    assert.equal(await pdf.isDisabled(), true);
    await page.getByLabel('Razão social *', { exact: true }).fill('Empresa Horizonte Exemplo');
    await page.getByLabel('Responsável do cliente *', { exact: true }).fill('Contato Exemplo');
    await page.getByLabel('Número da proposta *', { exact: true }).fill('V2-UI-001');
    await page.screenshot({ path: path.join(artifacts, '01-cliente-desktop.png') });
    await page.getByRole('button', { name: '2 Escopo', exact: true }).click();
    await page.getByRole('button', { name: 'PGR Gerenciamento de riscos', exact: true }).click();
    await page.getByRole('button', { name: '3 Comercial', exact: true }).click();
    await page.getByLabel('Investimento único (R$) *', { exact: true }).fill('1500,00');
    await page.waitForFunction(() => !document.querySelector('#editor-export').disabled, { timeout: 60000 });
    await page.screenshot({ path: path.join(artifacts, '02-comercial-preview.png') });
    assert.ok((await page.locator('#editor-pages').innerText()).includes('1.500,00'));
    await page.getByRole('button', { name: '1 Cliente', exact: true }).click();
    await page.getByLabel('Razão social *', { exact: true }).fill('Empresa Atualizada Exemplo');
    assert.equal(await pdf.isDisabled(), true);
    await page.waitForFunction(() => !document.querySelector('#editor-export').disabled);
    assert.ok((await page.locator('#editor-pages').innerText()).includes('Empresa Atualizada Exemplo'));
    await page.getByLabel('Tipo de cliente', { exact: true }).selectOption('group');
    await page.getByLabel('Nome do grupo *', { exact: true }).fill('Grupo Horizonte Exemplo');
    await page.getByLabel('Razão social *', { exact: true }).nth(1).fill('Unidade Norte Exemplo');
    await page.getByRole('button', { name: '+ Adicionar empresa', exact: true }).click();
    assert.equal(await page.getByLabel('Razão social *', { exact: true }).count(), 3);
    await page.getByRole('button', { name: 'Remover empresa', exact: true }).last().click();
    assert.equal(await page.getByLabel('Razão social *', { exact: true }).count(), 2);
    await page.getByRole('button', { name: '2 Escopo', exact: true }).click();
    await page.getByLabel('NR-01 / Integração', { exact: true }).check();
    const card = page.locator('.service-option').filter({ has: page.getByLabel('NR-01 / Integração', { exact: true }) });
    for (const input of await card.locator('input[type=number]').all()) await input.fill('1');
    await card.getByLabel(/Participantes/).fill('23');
    const company = page.locator('details.form-card').filter({ has: page.locator('summary', { hasText: 'Unidade Norte Exemplo' }) });
    await company.locator('summary').click();
    await company.getByLabel('Personalizar NR-01 / Integração', { exact: true }).check();
    await company.getByLabel(/Participantes/).fill('22');
    await page.screenshot({ path: path.join(artifacts, '03-escopo-grupo.png') });
    await page.getByRole('button', { name: '3 Comercial', exact: true }).click();
    await page.getByLabel('Tipo de cobrança', { exact: true }).selectOption('monthly');
    await page.getByLabel('Mensalidade (R$) *', { exact: true }).nth(0).fill('1800,00');
    await page.getByLabel('Mensalidade (R$) *', { exact: true }).nth(1).fill('1400,00');
    await page.waitForFunction(() => !document.querySelector('#editor-export').disabled, { timeout: 60000 });
    await page.getByRole('button', { name: '4 Revisão', exact: true }).click();
    const content = await page.locator('#editor-pages').innerText();
    assert.ok(content.includes('23') && content.includes('22'));
    assert.ok(content.includes('1.800,00') && content.includes('1.400,00'));
    assert.ok(!content.includes('Consolidado') && !content.includes('Valor contratual:'));
    await page.screenshot({ path: path.join(artifacts, '04-revisao-desktop.png') });
    await page.evaluate(() => { window.print = () => { window.printRequested = true; }; });
    await pdf.click();
    await page.waitForFunction(() => window.printRequested === true);
    const pageCount = await page.locator('.pagedjs_page').count();
    const output = await page.pdf({ path: path.join(artifacts, 'grupo-interface.pdf'), preferCSSPageSize: true, printBackground: true });
    assert.equal([...output.toString('latin1').matchAll(/\/Type\s*\/Page\b/g)].length, pageCount);
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: path.join(artifacts, '05-mobile-formulario.png') });
    await page.getByRole('button', { name: 'Ver preview', exact: true }).click();
    await page.screenshot({ path: path.join(artifacts, '06-mobile-preview.png') });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.waitForTimeout(200);
    assert.deepEqual(errors, []);
    await writeFile(path.join(artifacts, 'results.json'), JSON.stringify({ passed: true, pageCount, errors, scenarios: ['single', 'group', 'live-update', 'per-company-training', 'pricing-visibility', 'print', 'mobile'] }, null, 2));
    console.log('Interface: empresa única, grupo, atualização automática, parâmetros individuais, PDF e mobile aprovados.');
} catch (error) {
    if (page) { console.log(await page.locator('#editor-status').textContent()); await page.screenshot({ path: path.join(artifacts, 'failure.png') }); }
    throw error;
} finally { await browser?.close(); await server.close(); }
