import { chromium } from 'playwright';
import { createServer } from '../node_modules/vite/dist/node/index.js';
import { mkdir, writeFile, unlink } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';

const root = fileURLToPath(new URL('../', import.meta.url));
const directory = path.join(root, 'artifacts/v2-audit');
await mkdir(directory, { recursive: true });
const server = await createServer({ root, configFile: path.join(root, 'vite.config.ts'), server: { host: '127.0.0.1', port: 0, open: false, watch: { ignored: ['**/artifacts/**'] } } });
await server.listen();
let browser;
let page;
const errors = [];
const outbound = [];
try {
    browser = await chromium.launch();
    page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1 });
    page.on('pageerror', error => errors.push(error.message));
    page.on('request', request => { if (/^https?:/.test(request.url()) && new URL(request.url()).hostname !== '127.0.0.1') outbound.push(new URL(request.url()).origin); });
    await page.goto(`http://127.0.0.1:${server.httpServer.address().port}/gerador-de-proposta/v2.html`);
    const ready = () => page.waitForFunction(() => !document.querySelector('#editor-export').disabled, undefined, { timeout: 120000 });
    const step = name => page.getByRole('button', { name, exact: true }).click();
    await page.getByLabel('Tipo de cliente', { exact: true }).selectOption('group');
    await page.getByLabel('Nome do grupo *', { exact: true }).fill('Grupo de Homologação EngMarq');
    await page.getByLabel('Razão social *', { exact: true }).nth(0).fill('Unidade Industrial de Homologação');
    await page.getByLabel('Razão social *', { exact: true }).nth(1).fill('Unidade de Serviços de Homologação');
    await page.getByLabel('Responsável do cliente', { exact: true }).fill('Contato de Homologação');
    await page.getByLabel('Número da proposta *', { exact: true }).fill('V2-AUDIT-001');
    await step('2 Escopo');
    await page.getByLabel('Outros presets', { exact: true }).selectOption('assessoria-programas');
    assert.equal(await page.getByLabel('Ativar assessoria em SST').isChecked(), true);
    await page.getByLabel('NR-06 / EPI', { exact: true }).check();
    const training = page.locator('.service-option').filter({ has: page.getByLabel('NR-06 / EPI', { exact: true }) });
    for (const input of await training.locator('input[type=number]').all()) await input.fill('1');
    await training.getByLabel(/Participantes/).fill('10');
    await training.getByLabel(/Carga horária/).fill('2');
    await training.getByLabel('Público e perfil da capacitação').fill('Manutenção: reciclagem e prática supervisionada');
    const literal = '<img src=x onerror="window.auditInjected=true">';
    await training.getByLabel('Observações', { exact: true }).fill(literal);
    await page.getByLabel('Incluir visitas', { exact: true }).check();
    await page.getByLabel('Quantidade total de visitas *', { exact: true }).fill('12');
    await page.getByLabel('Duração por visita (horas) *', { exact: true }).fill('4');
    const second = page.locator('details.form-card').filter({ has: page.locator('summary', { hasText: 'Unidade de Serviços de Homologação' }) });
    await second.locator('summary').click();
    await second.getByLabel('Personalizar visitas', { exact: true }).check();
    await second.getByLabel('Quantidade total de visitas *', { exact: true }).fill('6');
    await second.getByLabel('Duração por visita (horas) *', { exact: true }).fill('2');
    await second.getByLabel('Frequência das visitas', { exact: true }).selectOption('quarterly');
    await page.getByLabel('Calor / IBUTG', { exact: true }).check();
    const measurement = page.locator('.service-option').filter({ has: page.getByLabel('Calor / IBUTG', { exact: true }) });
    await measurement.getByLabel(/Agente e tipo/).fill('Calor');
    await measurement.getByLabel(/Método previsto/).fill('IBUTG, conforme planejamento técnico');
    await measurement.getByLabel(/Quantidade contratada/).fill('1');
    await measurement.getByLabel(/Grupos e atividades/).fill('Cozinha');
    await measurement.getByLabel('Contratação', { exact: true }).selectOption('separate');
    await measurement.getByLabel('Observações', { exact: true }).fill('Dimensionar após visita; orçamento separado.');
    await step('3 Comercial');
    await page.getByLabel('Tipo de cobrança', { exact: true }).selectOption('both');
    await page.getByLabel('Investimento único (R$) *', { exact: true }).nth(0).fill('500');
    await page.getByLabel('Investimento único (R$) *', { exact: true }).nth(1).fill('300');
    await page.getByLabel('Mensalidade (R$) *', { exact: true }).nth(0).fill('1800');
    await page.getByLabel('Mensalidade (R$) *', { exact: true }).nth(1).fill('1400');
    assert.equal(await page.getByLabel('Vigência (meses) *', { exact: true }).count(), 0);
    await page.getByLabel('Quantidade de parcelas *', { exact: true }).fill('24');
    await ready();
    const content = await page.locator('#editor-pages').innerText();
    for (const expected of ['1.800,00', '1.400,00', '500,00', '300,00', '24 parcelas', '12 no contrato', '6 no contrato', 'Trimestral', 'Manutenção: reciclagem e prática supervisionada', 'Medições sujeitas a orçamento separado', literal]) assert.ok(content.includes(expected), `Texto ausente: ${expected}`);
    assert.doesNotMatch((await page.locator('#editor-pages .commercial-table').allTextContents()).join(' '), /vigência|\d+ meses/i);
    assert.ok(!content.includes('Consolidado') && !content.includes('Valor contratual:'));
    assert.equal(await page.locator('#editor-pages img[src="x"]').count(), 0);
    assert.equal(await page.evaluate(() => Boolean(window.auditInjected)), false);
    await page.getByLabel('Exibir total agregado', { exact: true }).check();
    await page.getByLabel('Exibir valor total do contrato', { exact: true }).check();
    await ready();
    assert.ok((await page.locator('#editor-pages').innerText()).includes('39.200,00'));
    await page.getByLabel('Exibir total agregado', { exact: true }).uncheck();
    await page.getByLabel('Exibir valor total do contrato', { exact: true }).uncheck();
    await ready();
    await step('4 Revisão');
    await page.screenshot({ path: path.join(directory, 'assistance-group-desktop.png') });
    await page.evaluate(() => { window.print = () => { window.auditPrint = true; }; });
    await page.locator('#editor-export').click();
    await page.waitForFunction(() => window.auditPrint, undefined, { timeout: 120000 });
    const pages = await page.locator('.pagedjs_page').count();
    const pdf = await page.pdf({ path: path.join(directory, 'assistance-group.pdf'), preferCSSPageSize: true, printBackground: true });
    assert.equal([...pdf.toString('latin1').matchAll(/\/Type\s*\/Page\b/g)].length, pages);
    await page.setViewportSize({ width: 390, height: 844 });
    await step('1 Cliente');
    const typingMs = await page.getByLabel('Nome do grupo *', { exact: true }).evaluate(input => {
        const started = performance.now();
        for (let index = 0; index < 60; index++) { input.value = `Grupo em edição ${index}`; input.dispatchEvent(new Event('input', { bubbles: true })); }
        return performance.now() - started;
    });
    assert.ok(typingMs < 500, `Digitação em grupo: ${typingMs}ms`);
    await ready();
    assert.ok((await page.locator('#editor-pages').innerText()).includes('Grupo em edição 59'));
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.screenshot({ path: path.join(directory, 'assistance-group-mobile.png') });
    const dialog = page.waitForEvent('dialog');
    const navigation = page.reload();
    const warning = await dialog;
    assert.equal(warning.type(), 'beforeunload');
    await warning.accept(); await navigation;
    assert.equal(await page.locator('#editor-export').isDisabled(), true);
    assert.deepEqual(errors, []); assert.deepEqual(outbound, []);
    await unlink(path.join(directory, 'failure.png')).catch(error => { if (error.code !== 'ENOENT') throw error; });
    await writeFile(path.join(directory, 'workflows.json'), JSON.stringify({ passed: true, pages, typingMs, errors, outbound, checks: ['assistance-group', 'training-audience', 'individual-visits', 'separate-measurement', 'once-monthly', 'contract-aggregate-visibility', 'literal-html', 'print', 'mobile-typing', 'beforeunload'] }, null, 2));
    console.log(`Auditoria de uso: assessoria/grupo, segurança, PDF e mobile aprovados; 60 eventos em ${typingMs.toFixed(1)}ms.`);
} catch (error) {
    if (page) await page.screenshot({ path: path.join(directory, 'failure.png') }).catch(() => undefined);
    await writeFile(path.join(directory, 'workflows.json'), JSON.stringify({ passed: false, error: error.stack, errors, outbound }, null, 2));
    throw error;
} finally { await browser?.close(); await server.close(); }